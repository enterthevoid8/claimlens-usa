"""Synthetic claim generator.

Produces US health plans, bill/discharge documents in several layouts with realistic noise, the
ground-truth structured data behind them, and a probabilistic "pended, denied or reduced" label.

IMPORTANT: the label is generated by *us*, from hard rule outcomes on the truth data plus soft latent
factors (price inflation, duplicates, hospital tendency, medical-records holds) and noise. Metrics on this data
show the pipeline works end to end and that the model learns signal beyond the rules; they say nothing
about real-world accuracy. See docs/MODEL_CARD.md.
"""

from __future__ import annotations

import math
import random
import zlib
from dataclasses import dataclass, field
from datetime import date, timedelta
from typing import Any

from claimlens.domain.models import (
    DischargeSummary,
    DocumentRef,
    DocumentType,
    ExtractedClaimData,
    HospitalBill,
    ItemCategory,
    LineItem,
    Policy,
    RuleStatus,
    Severity,
)
from claimlens.extraction.categorize import categorize
from claimlens.ml.anomaly import analyse_lines
from claimlens.rules.base import RuleContext, RuleEngine
from claimlens.rules.builtin import default_rules
from claimlens.rules.coding import dx_supports, make_npi
from claimlens.rules.policy_loader import instantiate_policy
from claimlens.synthetic import catalog as c

REF_TODAY = date(2026, 6, 30)

_KEY_VARIANTS = {
    "bill_number": ["Account No", "Patient Account No", "Invoice No"],
    "patient_name": ["Patient Name", "Patient", "Member Name"],
    "admission_date": ["Admission Date", "Admit Date", "Date of Admission", "DOA"],
    "discharge_date": ["Discharge Date", "Date of Discharge", "Through Date", "DOD"],
    "room_type": ["Room Type", "Accommodation"],
    "diagnosis_codes": ["Diagnosis Codes", "Dx Codes", "ICD Codes"],
    "procedure_code": ["Procedure Code", "Principal Procedure Code", "CPT Code"],
}
_TOTAL_LABELS = ["Grand Total", "Total Charges", "Total Billed Charges", "Total Amount"]
_DATE_FMTS = ["%m/%d/%Y", "%m-%d-%Y", "%b %d, %Y", "%Y-%m-%d"]
PRODUCTS = [("ppo_gold", 0.45), ("hmo_silver", 0.30), ("hdhp_bronze", 0.25)]
IN_NETWORK_SHARE = 80  # percent of hospitals in a tenant's network


def in_network(tenant_id: str, hospital_id: str) -> bool:
    return (zlib.crc32(f"{tenant_id}:{hospital_id}".encode()) % 100) < IN_NETWORK_SHARE


@dataclass
class SyntheticCase:
    case_id: str
    tenant_id: str
    policy: Policy
    documents: dict[str, str]
    truth_bill: HospitalBill
    truth_discharge: DischargeSummary | None
    hospital: c.Hospital
    label: int
    probability: float
    causes: list[str] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)


# ---------------------------------------------------------------- formatting helpers


def usd(n: float, decimals: int = 2) -> str:
    """US digit grouping: 1234567.5 -> 1,234,567.50"""
    return f"{n:,.{decimals}f}"


def make_hospitals(rng: random.Random, n: int = 40) -> list[c.Hospital]:
    names: set[str] = set()
    hospitals: list[c.Hospital] = []
    while len(hospitals) < n:
        name = f"{rng.choice(c.HOSPITAL_WORDS_A)} {rng.choice(c.HOSPITAL_WORDS_B)}"
        if name in names:
            continue
        names.add(name)
        layout = rng.choice(["pipe", "columns", "narrative"])
        city = rng.choice(list(c.METROS))
        hospitals.append(
            c.Hospital(
                hospital_id=f"H{len(hospitals):03d}",
                name=name,
                city=city,
                state=c.CITY_STATE[city],
                npi=make_npi("1" + "".join(str(rng.randint(0, 9)) for _ in range(8))),
                layout=layout,
                date_fmt=rng.choice(_DATE_FMTS),
                keys={k: rng.choice(v) for k, v in _KEY_VARIANTS.items()},
                total_label=rng.choice(_TOTAL_LABELS),
                propensity=rng.uniform(-0.7, 1.0),
                price_level=math.exp(rng.gauss(0.0, 0.12)),
                extra={"money": rng.choice(["dollar", "usd", "plain", "whole"])},
            )
        )
    return hospitals


def _money(n: float, style: str) -> str:
    return {
        "dollar": f"${usd(n)}",
        "usd": f"USD {usd(n)}",
        "plain": usd(n),
        "whole": f"${usd(n, 0)}",
    }[style]


def _round_price(x: float) -> float:
    return float(round(x / 5) * 5) if x > 100 else float(round(x))


# ---------------------------------------------------------------- bill construction


def _lognorm(rng: random.Random, sigma: float) -> float:
    return math.exp(rng.gauss(0.0, sigma))


def _build_items(
    rng: random.Random,
    proc: c.Procedure,
    hospital: c.Hospital,
    los: int,
    room_key: str,
    *,
    inflate: bool,
    duplicate: bool,
    unbundle: bool,
    days_over: bool,
) -> list[LineItem]:
    mult = c.CITY_MULTIPLIER[hospital.city] * hospital.price_level
    days = max(los, 1)
    items: list[LineItem] = []

    def add(desc: str, qty: float, unit: float, noise: float = 0.12) -> None:
        unit = _round_price(unit * mult * _lognorm(rng, noise))
        items.append(
            LineItem(
                description=desc,
                category=categorize(desc),
                quantity=qty,
                unit_price=unit,
                amount=round(qty * unit, 2),
            )
        )

    if proc.er_fee:
        add(c.ER_FEE_LABEL, 1, proc.base)
    if los > 0:
        label, base = c.ROOMS[room_key]
        add(label, days + (rng.randint(2, 4) if days_over else 0), base)
        if rng.random() < proc.icu_prob:
            add(
                rng.choice(c.GENERIC_ITEMS["icu"][0]),
                rng.randint(1, max(1, min(3, days))),
                c.GENERIC_ITEMS["icu"][1],
            )
        add(rng.choice(c.GENERIC_ITEMS["nursing"][0]), days, c.GENERIC_ITEMS["nursing"][1])
        add(
            rng.choice(c.GENERIC_ITEMS["doctor_visit"][0]), days, c.GENERIC_ITEMS["doctor_visit"][1]
        )
    add(rng.choice(c.GENERIC_ITEMS["registration"][0]), 1, c.GENERIC_ITEMS["registration"][1], 0.05)
    add(
        rng.choice(c.GENERIC_ITEMS["documentation"][0]),
        1,
        c.GENERIC_ITEMS["documentation"][1],
        0.05,
    )
    for d in proc.diagnostics:
        names, price, _ = c.GENERIC_ITEMS[d]
        add(rng.choice(names), rng.choice([1, 1, 1, 2]), price)
    for m in proc.medicines:
        names, price, _ = c.GENERIC_ITEMS[m]
        qty = days if m == "pharmacy" else rng.randint(2, 3 * days + 2)
        add(rng.choice(names), qty, price)

    surgical = proc.kind != "medical"
    if surgical:
        parts = ["surgeon", "anesthesia", "or", "consumables"] + (
            ["implant"] if proc.implant else []
        )
        if unbundle:
            add(f"{c.PACKAGE_LABEL} - {proc.procedure}", 1, proc.base * 0.9)
        for part in parts:  # when unbundling, components are billed on top of the package
            label, share, _ = c.PROC_ITEMS[part]
            add(f"{label} - {proc.procedure}", 1, proc.base * share, 0.14)
    if inflate:
        pool = [i for i in items if i.category not in (ItemCategory.ADMIN,) and i.amount > 400]
        for it in rng.sample(pool, k=min(len(pool), rng.randint(1, 3))):
            f = rng.uniform(1.8, 3.4)
            it.unit_price = _round_price((it.unit_price or it.amount) * f)
            it.amount = round(it.quantity * it.unit_price, 2)
    if duplicate:
        dup_pool = [
            i
            for i in items
            if i.category
            in (
                ItemCategory.DIAGNOSTIC,
                ItemCategory.SURGEON,
                ItemCategory.OR,
                ItemCategory.DOCTOR_FEE,
            )
        ]
        if dup_pool:
            items.append(rng.choice(dup_pool).model_copy())
    return items


# ---------------------------------------------------------------- rendering


def _render_items(hospital: c.Hospital, items: list[LineItem]) -> list[str]:
    style = hospital.extra["money"]
    lines: list[str] = []
    if hospital.layout == "pipe":
        lines.append("| Line | Description | Qty | Rate | Amount |")
        lines.append("|---|---|---|---|---|")
        for n, it in enumerate(items, 1):
            lines.append(
                f"| {n} | {it.description} | {it.quantity:g} | {_money(it.unit_price or it.amount, style)} | {_money(it.amount, style)} |"
            )
    elif hospital.layout == "columns":
        lines.append("Line  Description                              Qty    Rate        Amount")
        for n, it in enumerate(items, 1):
            lines.append(
                f"{n:<5} {it.description:<40}  {it.quantity:g}   {usd(it.unit_price or it.amount)}   {usd(it.amount)}"
            )
    else:
        for n, it in enumerate(items, 1):
            dots = "." * max(3, 62 - len(it.description))
            lines.append(
                f"{n}. {it.description} ({it.quantity:g} x ${usd(it.unit_price or it.amount)}) {dots} ${usd(it.amount)}"
            )
    return lines


def _dfmt(d: date | None, fmt: str) -> str:
    return d.strftime(fmt) if d else ""


def _print_code(code: str) -> str:
    return f"DRG {code[3:]}" if code.startswith("DRG") else code


def render_bill(
    rng: random.Random,
    hospital: c.Hospital,
    bill: HospitalBill,
    *,
    noise: float,
    omit_bill_no: bool,
    omit_dod: bool,
) -> str:
    k = hospital.keys
    out = [
        hospital.name,
        f"City: {hospital.city}",
        f"State: {hospital.state}",
        "ITEMIZED HOSPITAL BILL (UB-04 SUMMARY)",
        f"Facility NPI: {bill.provider_npi}",
    ]
    if not omit_bill_no:
        out.append(f"{k['bill_number']}: {bill.bill_number}")
    out.append(f"{k['patient_name']}: {bill.patient_name}")
    out.append(f"{k['admission_date']}: {_dfmt(bill.admission_date, hospital.date_fmt)}")
    if not omit_dod:
        out.append(f"{k['discharge_date']}: {_dfmt(bill.discharge_date, hospital.date_fmt)}")
    if bill.room_type:
        out.append(f"{k['room_type']}: {bill.room_type}")
    out.append(f"Diagnosis: {bill.diagnosis}")
    if bill.diagnosis_codes:
        out.append(f"{k['diagnosis_codes']}: {', '.join(bill.diagnosis_codes)}")
    out.append(f"Procedure: {bill.procedure}")
    if bill.procedure_code:
        out.append(f"{k['procedure_code']}: {_print_code(bill.procedure_code)}")
    out.append("")
    body = _render_items(hospital, bill.line_items)
    for i, line in enumerate(body):
        if (
            i > 1 and rng.random() < noise
        ):  # OCR-like damage to one number: the line becomes unreadable
            line = _corrupt_number(rng, line)
        out.append(line)
    out.append("")
    total = (
        _money(bill.total_claimed or 0, hospital.extra["money"])
        if hospital.layout != "columns"
        else usd(bill.total_claimed or 0)
    )
    out.append(f"{hospital.total_label}: {total}")
    out.append("Authorized signatory")
    return "\n".join(out)


def _corrupt_number(rng: random.Random, line: str) -> str:
    idx = [i for i, ch in enumerate(line) if ch.isdigit()]
    if not idx:
        return line
    i = rng.choice(idx[-6:])
    return line[:i] + rng.choice("OlI") + line[i + 1 :]


def render_discharge(
    rng: random.Random,
    hospital: c.Hospital,
    d: DischargeSummary,
    patient_name: str,
) -> str:
    fmt = rng.choice(_DATE_FMTS)
    out = [
        hospital.name,
        "DISCHARGE SUMMARY",
        f"Patient Name: {patient_name}",
        f"Admission Date: {_dfmt(d.admission_date, fmt)}",
        f"Discharge Date: {_dfmt(d.discharge_date, fmt)}",
        f"Admission Type: {'Emergency' if d.is_emergency else 'Elective'}",
        f"Cause: {'Accident' if d.is_accident else 'Illness'}",
    ]
    if d.third_party_liability is not None:
        out.append(f"Third Party Liability: {'Yes' if d.third_party_liability else 'No'}")
    out.append(f"Diagnosis: {d.diagnosis}")
    if d.diagnosis_codes:
        out.append(f"Diagnosis Codes: {', '.join(d.diagnosis_codes)}")
    out += [
        f"Procedure Performed: {d.procedure}",
        f"Attending Physician: {d.treating_doctor}",
        "Condition at Discharge: Stable",
        "Advice on Discharge: Follow up with primary care within one week",
    ]
    return "\n".join(out)


def render_preauth(rng: random.Random, hospital: c.Hospital, policy: Policy, amount: float) -> str:
    return "\n".join(
        [
            "PRIOR AUTHORIZATION APPROVAL",
            "Utilization management determination: approved",
            f"Authorization number: PA-{rng.randint(1000000, 9999999)}",
            f"Plan: {policy.policy_id}",
            f"Facility: {hospital.name}",
            f"Approved amount: ${usd(amount)}",
        ]
    )


# ---------------------------------------------------------------- the case generator


def _pick(rng: random.Random, weighted: list[tuple[str, float]]) -> str:
    r, acc = rng.random() * sum(w for _, w in weighted), 0.0
    for v, w in weighted:
        acc += w
        if r <= acc:
            return v
    return weighted[-1][0]


def _sigmoid(x: float) -> float:
    return 1 / (1 + math.exp(-x))


def generate_case(
    rng: random.Random,
    hospitals: list[c.Hospital],
    idx: int,
    tenant_id: str = "tenant1",
    noise: float = 0.015,
    as_of: date = REF_TODAY,
) -> SyntheticCase:
    case_id = f"syn{idx:06d}"
    network = [h for h in hospitals if in_network(tenant_id, h.hospital_id)]
    hospital = rng.choice(network if network and rng.random() < 0.92 else hospitals)
    weights = [
        (p.key, 0.25 if p.key in ("rhinoplasty", "bariatric") else 1.0) for p in c.PROCEDURES
    ]
    proc_key = _pick(rng, weights)
    proc = next(p for p in c.PROCEDURES if p.key == proc_key)
    first, last = rng.choice(c.FIRST_NAMES), rng.choice(c.LAST_NAMES)
    patient = f"{first} {last}"
    holder = patient if rng.random() < 0.65 else f"{rng.choice(c.FIRST_NAMES)} {last}"

    # --- timing and plan
    long_stay = proc.kind != "daycare" and proc.los[1] > 0 and rng.random() < 0.03
    los = (
        0
        if proc.kind == "daycare" and rng.random() < 0.8
        else rng.randint(*proc.los)
        if proc.los[1] > 0
        else 0
    )
    if long_stay:
        los = proc.los[1] + rng.randint(3, 6)
    bucket = rng.random()
    lag = (
        rng.randint(3, 75)
        if bucket < 0.86
        else rng.randint(76, 200)
        if bucket < 0.95
        else rng.randint(201, 520)
    )
    dis = as_of - timedelta(days=lag)
    adm = dis - timedelta(days=los)
    bucket = rng.random()
    age_days = (
        rng.randint(0, 25)
        if bucket < 0.12
        else rng.randint(26, 700)
        if bucket < 0.30
        else rng.randint(700, 2500)
    )
    start = adm - timedelta(days=age_days)
    product = _pick(rng, PRODUCTS)
    policy = instantiate_policy(
        product,
        policy_id=f"POL{idx:06d}",
        tenant_id=tenant_id,
        holder_name=holder,
        start_date=start,
        term_years=max(1, math.ceil((age_days + los + 1) / 365)),
        network_providers=[h.name for h in network],
    )
    policy.deductible_met = policy.deductible * rng.choice([0.0, 0.25, 0.6, 1.0])
    policy.oop_met = min(policy.oop_max, policy.deductible_met * rng.choice([1.0, 1.5, 2.0]))
    if rng.random() < 0.02:  # coverage terminated before the stay
        policy.end_date = adm - timedelta(days=rng.randint(5, 60))

    # --- clinical facts
    emergency = rng.random() < proc.emergency_prob
    liability: bool | None = None
    if proc.accident and rng.random() > 0.2:  # the form usually (not always) answers the question
        liability = rng.random() < proc.liability_prob

    # --- bill
    room_key = rng.choices(list(c.ROOMS), weights=[0.50, 0.30, 0.15, 0.05])[0]
    p_inflate = 0.10 + (0.25 if hospital.price_level > 1.15 else 0.0)
    flags = {
        "inflate": rng.random() < p_inflate,
        "duplicate": rng.random() < 0.04,
        "unbundle": proc.kind == "surgical" and rng.random() < 0.04,
        "days_over": los > 0 and rng.random() < 0.03,
        "long_stay": long_stay,
        "dx_mismatch": rng.random() < 0.04,
        "bad_code_format": rng.random() < 0.02,
        "bad_npi": rng.random() < 0.015,
        "omit_codes": rng.random() < 0.03,
    }
    items = _build_items(
        rng,
        proc,
        hospital,
        los,
        room_key,
        inflate=flags["inflate"],
        duplicate=flags["duplicate"],
        unbundle=flags["unbundle"],
        days_over=flags["days_over"],
    )
    total = round(sum(i.amount for i in items), 2)
    arithmetic_error = rng.random() < 0.04
    if arithmetic_error:
        total = round(total * rng.choice([0.9, 0.93, 1.07, 1.12]), 0)
    discharge_patient = patient
    if rng.random() < 0.03:
        discharge_patient = f"{rng.choice(c.FIRST_NAMES)} {rng.choice(c.LAST_NAMES)}"

    true_dx = list(proc.icd[: rng.randint(1, len(proc.icd))])
    bill_dx = list(true_dx)
    if flags["dx_mismatch"]:
        wrong = [
            p.icd[0]
            for p in c.PROCEDURES
            if p.key != proc.key and dx_supports(proc.code, [p.icd[0]]) is False
        ]
        if wrong:  # procedures that accept any diagnosis (e.g. an ER visit) cannot be mismatched
            bill_dx = [rng.choice(wrong)]
        else:
            flags["dx_mismatch"] = False
    if flags["bad_code_format"]:
        bill_dx = [bill_dx[0].replace(".", ""), *bill_dx[1:]]
    npi = hospital.npi
    if flags["bad_npi"]:
        npi = npi[:9] + str((int(npi[9]) + rng.randint(1, 9)) % 10)
    if flags["omit_codes"]:
        bill_dx, bill_code = [], None
    else:
        bill_code = proc.code
    bill = HospitalBill(
        bill_number=f"AC-{rng.randint(1000000, 9999999)}",
        hospital_name=hospital.name,
        provider_npi=npi,
        city=hospital.city,
        state=hospital.state,
        patient_name=patient,
        admission_date=adm,
        discharge_date=dis,
        diagnosis=proc.diagnosis,
        procedure=proc.procedure,
        diagnosis_codes=bill_dx,
        procedure_code=bill_code,
        room_type=c.ROOM_LABEL[room_key] if los > 0 else None,
        line_items=items,
        total_claimed=total,
    )
    discharge = DischargeSummary(
        patient_name=discharge_patient,
        diagnosis=proc.diagnosis,
        procedure=proc.procedure,
        admission_date=adm,
        discharge_date=dis,
        diagnosis_codes=true_dx,
        is_emergency=emergency,
        is_accident=proc.accident,
        third_party_liability=liability,
        treating_doctor=rng.choice(c.DOCTORS),
    )

    documents: dict[str, str] = {}
    omit_bn, omit_dod = rng.random() < 0.02, rng.random() < 0.015
    documents["bill.txt"] = render_bill(
        rng, hospital, bill, noise=noise, omit_bill_no=omit_bn, omit_dod=omit_dod
    )
    has_discharge = rng.random() > 0.06
    if has_discharge:
        documents["discharge_summary.txt"] = render_discharge(
            rng, hospital, discharge, discharge_patient
        )
    text = f"{proc.diagnosis} {proc.procedure}".lower()
    needs_preauth = (not emergency) and (
        total > policy.preauth_required_above or any(k in text for k in policy.preauth_keywords)
    )
    has_preauth = needs_preauth and rng.random() < 0.72
    if has_preauth:
        documents["preauth_approval.txt"] = render_preauth(rng, hospital, policy, total)

    # --- label from truth data (what a careful payer would conclude) + latent factors
    refs = [
        DocumentRef(
            filename=n, content_type="text/plain", blob_path=n, sha256="0", size_bytes=1, doc_type=t
        )
        for n, t in [
            ("bill.txt", DocumentType.HOSPITAL_BILL),
            *([("discharge_summary.txt", DocumentType.DISCHARGE_SUMMARY)] if has_discharge else []),
            *([("preauth_approval.txt", DocumentType.PREAUTH_APPROVAL)] if has_preauth else []),
        ]
    ]
    truth_data = ExtractedClaimData(
        bill=bill,
        discharge=discharge if has_discharge else None,
        has_preauth_approval=has_preauth,
        extraction_confidence=1.0,
        extractor="truth",
    )
    results = RuleEngine(default_rules()).run(
        RuleContext(policy=policy, data=truth_data, documents=refs, today=as_of)
    )
    blockers = [
        r for r in results if r.status == RuleStatus.FAIL and r.severity == Severity.BLOCKER
    ]
    warns = [r for r in results if r.status == RuleStatus.FAIL and r.severity == Severity.WARN]
    la = analyse_lines(bill)
    share_cons = sum(i.amount for i in items if i.category == ItemCategory.CONSUMABLE) / max(
        total, 1
    )
    records_hold = total > 40_000 and rng.random() < 0.10
    logit = -2.9
    logit += 3.0 if blockers else 0.0
    logit += 1.2 if warns else 0.0
    logit += 0.55 * min(la.price_z_mean, 4.0)
    logit += (
        1.4 * (la.n_duplicates > 0) + 1.1 * (la.n_unbundling > 0) + 0.9 * (la.n_days_over_stay > 0)
    )
    logit += 0.9 * (share_cons > 0.22) + 0.8 * hospital.propensity + 1.8 * records_hold
    logit += rng.gauss(0, 0.4)
    prob = _sigmoid(logit)
    label = int(rng.random() < prob)
    causes = [r.rule_id for r in blockers + warns]
    for name, cause in (
        ("inflate", "inflated_prices"),
        ("duplicate", "duplicate_line"),
        ("unbundle", "unbundled_package"),
        ("days_over", "days_exceed_stay"),
    ):
        if flags[name]:
            causes.append(cause)
    if records_hold:
        causes.append("records_request")
    return SyntheticCase(
        case_id=case_id,
        tenant_id=tenant_id,
        policy=policy,
        documents=documents,
        truth_bill=bill,
        truth_discharge=discharge if has_discharge else None,
        hospital=hospital,
        label=label,
        probability=prob,
        causes=causes,
        meta={
            "procedure": proc.key,
            "product": product,
            "omit_bill_no": omit_bn,
            "omit_dod": omit_dod,
            "market_tier": c.CITY_TIER[hospital.city],
            "flags": flags,
            "as_of": as_of.isoformat(),
        },
    )


def generate_dataset(
    n: int, seed: int = 42, tenant_id: str = "tenant1", as_of: date = REF_TODAY
) -> list[SyntheticCase]:
    rng = random.Random(seed)
    hospitals = make_hospitals(random.Random(seed + 1))
    return [generate_case(rng, hospitals, i, tenant_id, as_of=as_of) for i in range(n)]
